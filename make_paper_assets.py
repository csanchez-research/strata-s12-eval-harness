#!/usr/bin/env python
r"""
make_paper_assets.py - generates the WHOLE probe-assets folder for the paper from
the results JSON. A single command produces reben/ with vars/, figs/, tables/ and
scripts/ ready for \input and \includegraphics.

Single source of numbers: summary.json + probe_results.json. Nothing is typed by
hand; re-running after a new run updates everything.

Usage:
    python make_paper_assets.py --summary summary.json --results probe_results.json \
        --out-root /path/to/paper_repo --git d6037a5


Generated structure:
    reben/
      vars/   probe_vars.tex          (\newcommand for each number)
      figs/   probe_main.pdf/.png     (main figure: grouped bars + points)
              probe_per_class.pdf/.png (19-class breakdown, if per_class_ap)
      tables/ probe_table.tex         (micro/macro table, no fixed numbering)
      scripts/ copies of the generators (reproducibility)

"""
from __future__ import annotations

import argparse
import json
import shutil
from pathlib import Path

import matplotlib
import numpy as np

matplotlib.use("Agg")
import matplotlib.pyplot as plt

PRE = "#2a7f62"
RND = "#9a9a9a"

# reBEN 19 class names, fixed order (same as reben_loader.py)
REBEN_19 = [
    "Agro-forestry areas", "Arable land", "Beaches, dunes, sands",
    "Broad-leaved forest", "Coastal wetlands", "Complex cultivation patterns",
    "Coniferous forest", "Industrial or commercial units", "Inland waters",
    "Inland wetlands", "Land principally occ. by agriculture", "Marine waters",
    "Mixed forest", "Moors, heathland, sclerophyllous", "Natural grassland/sparse veg.",
    "Pastures", "Permanent crops", "Transitional woodland, shrub", "Urban fabric",
]


def _save(fig, d, name):
    fig.tight_layout()
    fig.savefig(d / f"{name}.pdf")
    fig.savefig(d / f"{name}.png", dpi=150)
    plt.close(fig)


# ---------- VARIABLES ----------
def gen_vars(s, r, out, git, epoch, max_train, seed):
    def f4(x): return f"{x:.4f}"
    mi_p, mi_ps = s["micro_mAP"]["pretrained"]
    mi_r, mi_rs = s["micro_mAP"]["random"]
    ma_p, ma_ps = s["macro_mAP"]["pretrained"]
    ma_r, ma_rs = s["macro_mAP"]["random"]
    nv = r["pretrained"][0]["n_classes_valid"]
    nt = r["pretrained"][0]["n_classes_total"]
    L = [
        "% probe_vars.tex - generated by make_paper_assets.py. Do NOT edit by hand.",
        f"\\newcommand{{\\ProbeMicroPre}}{{{f4(mi_p)}}}",
        f"\\newcommand{{\\ProbeMicroRnd}}{{{f4(mi_r)}}}",
        f"\\newcommand{{\\ProbeMacroPre}}{{{f4(ma_p)}}}",
        f"\\newcommand{{\\ProbeMacroRnd}}{{{f4(ma_r)}}}",
        f"\\newcommand{{\\ProbeMicroPreFull}}{{{f4(mi_p)}\\,$\\pm$\\,{f4(mi_ps)}}}",
        f"\\newcommand{{\\ProbeMicroRndFull}}{{{f4(mi_r)}\\,$\\pm$\\,{f4(mi_rs)}}}",
        f"\\newcommand{{\\ProbeMacroPreFull}}{{{f4(ma_p)}\\,$\\pm$\\,{f4(ma_ps)}}}",
        f"\\newcommand{{\\ProbeMacroRndFull}}{{{f4(ma_r)}\\,$\\pm$\\,{f4(ma_rs)}}}",
        f"\\newcommand{{\\ProbeMicroDelta}}{{{f4(mi_p - mi_r)}}}",
        f"\\newcommand{{\\ProbeMacroDelta}}{{{f4(ma_p - ma_r)}}}",
        f"\\newcommand{{\\ProbeCriterion}}{{{'passed' if s['criterion_passed'] else 'not passed'}}}",
        f"\\newcommand{{\\ProbeCriterionMargin}}{{{f4(s['criterion_margin'])}}}",
        f"\\newcommand{{\\ProbeSeeds}}{{{s['n_seeds']}}}",
        f"\\newcommand{{\\ProbeClassesValid}}{{{nv}}}",
        f"\\newcommand{{\\ProbeClassesTotal}}{{{nt}}}",
        f"\\newcommand{{\\ProbeMaxTrain}}{{{max_train:,}}}".replace(",", "{,}"),
        f"\\newcommand{{\\ProbeTrainSeed}}{{{seed}}}",
        f"\\newcommand{{\\ProbeEncoderEpoch}}{{{epoch}}}",
        f"\\newcommand{{\\ProbeGitHash}}{{{git}}}",
        "",
    ]
    (out / "probe_vars.tex").write_text("\n".join(L), encoding="utf-8")
    return len([x for x in L if x.startswith("\\newcommand")])


# ---------- TABLE ----------
def gen_table(s, out):
    def f4(x): return f"{x:.4f}"
    mi_p, mi_ps = s["micro_mAP"]["pretrained"]
    mi_r, mi_rs = s["micro_mAP"]["random"]
    ma_p, ma_ps = s["macro_mAP"]["pretrained"]
    ma_r, ma_rs = s["macro_mAP"]["random"]
    n = s["n_seeds"]
    tex = [
        "% probe_table.tex - generated by make_paper_assets.py. No fixed numbering: LaTeX numbers."
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Frozen linear-probe performance on reBEN (BigEarthNet v2.0, "
        f"19-class multi-label), mean $\\pm$ std over {n} seeds. The pre-registered "
        "criterion holds when $\\mathrm{mean}_{pre}-\\mathrm{std}_{pre}$ exceeds "
        "$\\mathrm{mean}_{rnd}+\\mathrm{std}_{rnd}$ on micro-mAP.}",
        "\\label{tab:probe}",
        "\\begin{tabular}{lcc}",
        "\\toprule",
        "Metric & Pre-trained on $D$ & Random init \\\\",
        "\\midrule",
        f"micro-mAP (primary) & ${f4(mi_p)} \\pm {f4(mi_ps)}$ & ${f4(mi_r)} \\pm {f4(mi_rs)}$ \\\\",
        f"macro-mAP & ${f4(ma_p)} \\pm {f4(ma_ps)}$ & ${f4(ma_r)} \\pm {f4(ma_rs)}$ \\\\",
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
        "",
    ]
    (out / "probe_table.tex").write_text("\n".join(tex), encoding="utf-8")


# ---------- MAIN FIGURE (grouped bars + points) ----------
def gen_main_fig(s, r, out):
    fig, ax = plt.subplots(figsize=(5.2, 4))
    keys = ["micro_mAP", "macro_mAP"]
    labels = ["micro-mAP", "macro-mAP"]
    pre = [s[k]["pretrained"][0] for k in keys]
    pre_s = [s[k]["pretrained"][1] for k in keys]
    rnd = [s[k]["random"][0] for k in keys]
    rnd_s = [s[k]["random"][1] for k in keys]
    x = np.arange(2)
    w = 0.35
    ax.bar(x - w/2, pre, w, yerr=pre_s, capsize=5, color=PRE, label="Pre-trained on $D$", alpha=0.9)
    ax.bar(x + w/2, rnd, w, yerr=rnd_s, capsize=5, color=RND, label="Random init", alpha=0.9)
    for j, k in enumerate(keys):
        for row in r["pretrained"]:
            ax.scatter(x[j]-w/2, row[k], color="black", s=12, zorder=3)
        for row in r["random"]:
            ax.scatter(x[j]+w/2, row[k], color="black", s=12, zorder=3)
    ax.set_xticks(x)
    ax.set_xticklabels(labels)
    ax.set_ylabel("mAP")
    ax.set_ylim(0, 0.62)
    ax.legend(frameon=False)
    ax.grid(axis="y", alpha=0.3)
    ax.set_title("Frozen linear probe on reBEN (3 seeds)")
    _save(fig, out, "probe_main")


# ---------- PER-CLASS FIGURE (if per_class_ap) ----------
def gen_per_class_fig(r, out):
    # per-class AP averaged over seeds, pre and random
    def mean_per_class(which):
        acc: dict[int, list] = {}
        for row in r[which]:
            pca = row.get("per_class_ap") or {}
            for c, ap in pca.items():
                acc.setdefault(int(c), []).append(ap)
        return {c: float(np.mean(v)) for c, v in acc.items()}

    pre = mean_per_class("pretrained")
    rnd = mean_per_class("random")
    if not pre or not rnd:
        return False  # no per_class_ap yet

    classes = sorted(set(pre) & set(rnd))
    # sort by pre-rnd difference (largest improvement on top)
    classes.sort(key=lambda c: pre[c] - rnd[c])
    names = [REBEN_19[c] if c < len(REBEN_19) else f"class {c}" for c in classes]
    y = np.arange(len(classes))

    fig, ax = plt.subplots(figsize=(7.5, 6.8))
    for i, c in enumerate(classes):
        ax.plot([rnd[c], pre[c]], [i, i], color="#ccc", lw=2, zorder=1)
    ax.scatter([rnd[c] for c in classes], y, color=RND, s=40, label="Random init", zorder=2)
    ax.scatter([pre[c] for c in classes], y, color=PRE, s=40, label="Pre-trained on $D$", zorder=2)
    ax.set_yticks(y)
    ax.set_yticklabels(names, fontsize=8)
    ax.set_xlabel("Average precision (AP)")
    ax.set_title("Per-class AP on reBEN (3-seed mean)", pad=28)
    ax.legend(frameon=False, loc="lower center", bbox_to_anchor=(0.5, 1.08),
              ncol=2)
    ax.grid(axis="x", alpha=0.3)
    _save(fig, out, "probe_per_class")
    return True


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--summary", default="summary.json")
    ap.add_argument("--results", default="probe_results.json")
    ap.add_argument("--out-root", default=".", help="paper repo; reben/ is created inside")
    ap.add_argument("--git", default="d6037a5")
    ap.add_argument("--epoch", type=int, default=100)
    ap.add_argument("--max-train", type=int, default=40000)
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--scripts", nargs="*", default=[],
                    help="paths of generator scripts to copy into reben/scripts/")
    args = ap.parse_args()

    with open(args.summary) as fh:
        s = json.load(fh)
    with open(args.results) as fh:
        r = json.load(fh)

    root = Path(args.out_root) / "reben"
    vars_d = root / "vars"
    figs_d = root / "figs"
    tab_d = root / "tables"
    scr_d = root / "scripts"
    for d in (vars_d, figs_d, tab_d, scr_d):
        d.mkdir(parents=True, exist_ok=True)

    nvars = gen_vars(s, r, vars_d, args.git, args.epoch, args.max_train, args.seed)
    gen_table(s, tab_d)
    gen_main_fig(s, r, figs_d)
    has_pc = gen_per_class_fig(r, figs_d)

    for sp in args.scripts:
        if Path(sp).exists():
            shutil.copyfile(sp, scr_d / Path(sp).name)

    print(f"=== reben/ generated in {root} ===")
    print(f"  vars/probe_vars.tex      ({nvars} variables)")
    print("  tables/probe_table.tex")
    print("  figs/probe_main.pdf/.png")
    if has_pc:
        print("  figs/probe_per_class.pdf/.png")
    else:
        print("  figs/probe_per_class  -> SKIPPED (per_class_ap missing;")
        print("     re-run linear_probe.py and launch make_paper_assets.py again)")
    if args.scripts:
        print(f"  scripts/ ({len([x for x in args.scripts if Path(x).exists()])} copied)")


if __name__ == "__main__":
    main()
