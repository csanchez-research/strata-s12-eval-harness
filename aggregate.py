"""
aggregate.py - combines the seeds, applies the pre-registered non-overlap
criterion and generates the probe's table (LaTeX) and figure.
The files are written WITHOUT a number: LaTeX numbers them at compile time via
input and ref{tab:probe} / ref{fig:probe}. Do not hardcode the number here.

Criterion (paper §5.1): averaged over seeds, the pre-trained encoder must beat
the random-init one by more than the two combined error bars:
    mean_pre - std_pre > mean_rnd + std_rnd   (on micro-mAP)
This is a conservative 1-sigma non-overlap rule.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np


def _stats(rows: list[dict], key: str) -> tuple[float, float]:
    vals = np.array([r[key] for r in rows], dtype=np.float64)
    return float(vals.mean()), float(vals.std())


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default="out/probe_results.json")
    ap.add_argument("--out-dir", default="out")
    args = ap.parse_args()

    with open(args.results) as f:
        res = json.load(f)

    out = Path(args.out_dir)
    out.mkdir(parents=True, exist_ok=True)

    pre = res["pretrained"]
    rnd = res["random"]
    n_seeds = len(pre)

    pre_micro_m, pre_micro_s = _stats(pre, "micro_mAP")
    rnd_micro_m, rnd_micro_s = _stats(rnd, "micro_mAP")
    pre_macro_m, pre_macro_s = _stats(pre, "macro_mAP")
    rnd_macro_m, rnd_macro_s = _stats(rnd, "macro_mAP")

    # 1-sigma non-overlap criterion on micro-mAP (the primary metric)
    lhs = pre_micro_m - pre_micro_s
    rhs = rnd_micro_m + rnd_micro_s
    passed = lhs > rhs
    margin = lhs - rhs

    print(f"seeds: {n_seeds}")
    print(f"micro-mAP  pre {pre_micro_m:.4f}±{pre_micro_s:.4f}  "
          f"rnd {rnd_micro_m:.4f}±{rnd_micro_s:.4f}")
    print(f"macro-mAP  pre {pre_macro_m:.4f}±{pre_macro_s:.4f}  "
          f"rnd {rnd_macro_m:.4f}±{rnd_macro_s:.4f}")
    print("\ncriterion (mean_pre - std_pre > mean_rnd + std_rnd):")
    print(f"  {lhs:.4f} > {rhs:.4f}  ->  "
          f"{'CUMPLIDO' if passed else 'NO cumplido'} (margen {margin:+.4f})")

    # --- probe figure ---
    tex = [
        "% Probe table - generated by aggregate.py",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Frozen linear-probe performance on reBEN (BigEarthNet v2.0, "
        f"19-class multi-label), mean $\\pm$ std over {n_seeds} seeds. "
        "The pre-registered criterion is met when "
        "$\\mathrm{mean}_{pre}-\\mathrm{std}_{pre}$ exceeds "
        "$\\mathrm{mean}_{rnd}+\\mathrm{std}_{rnd}$ on micro-mAP.}",
        "\\label{tab:probe}",
        "\\begin{tabular}{lcc}",
        "\\toprule",
        "Metric & Pre-trained on $D$ & Random init \\\\",
        "\\midrule",
        f"micro-mAP (primary) & ${pre_micro_m:.4f} \\pm {pre_micro_s:.4f}$ & "
        f"${rnd_micro_m:.4f} \\pm {rnd_micro_s:.4f}$ \\\\",
        f"macro-mAP (descriptor) & ${pre_macro_m:.4f} \\pm {pre_macro_s:.4f}$ & "
        f"${rnd_macro_m:.4f} \\pm {rnd_macro_s:.4f}$ \\\\",
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
        "",
    ]
    (out / "probe_table.tex").write_text("\n".join(tex), encoding="utf-8")

    # --- figura del probe ---
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt

        fig, ax = plt.subplots(figsize=(5, 4))
        x = [0, 1]
        means = [pre_micro_m, rnd_micro_m]
        stds = [pre_micro_s, rnd_micro_s]
        ax.bar(x, means, yerr=stds, capsize=6,
               color=["#2a7", "#999"], width=0.6)
        ax.set_xticks(x)
        ax.set_xticklabels(["Pre-trained on $D$", "Random init"])
        ax.set_ylabel("micro-mAP")
        ax.set_title(f"Frozen linear probe on reBEN ({n_seeds} seeds)")
        ax.grid(axis="y", alpha=0.3)
        fig.tight_layout()
        fig.savefig(out / "probe_figure.pdf")
        fig.savefig(out / "probe_figure.png", dpi=150)
        print(f"\nProbe table -> {out/'probe_table.tex'}")
        print(f"Probe figure -> {out/'probe_figure.pdf'} (+ .png)")

    except Exception as e:
        print(f"\n(matplotlib unavailable for the figure: {e})")
        print(f"Probe table -> {out/'probe_table.tex'}")


    # --- JSON summary ---
    summary = {
        "n_seeds": n_seeds,
        "micro_mAP": {"pretrained": [pre_micro_m, pre_micro_s],
                      "random": [rnd_micro_m, rnd_micro_s]},
        "macro_mAP": {"pretrained": [pre_macro_m, pre_macro_s],
                      "random": [rnd_macro_m, rnd_macro_s]},
        "criterion_passed": bool(passed),
        "criterion_margin": float(margin),
    }
    (out / "summary.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")


if __name__ == "__main__":
    main()
